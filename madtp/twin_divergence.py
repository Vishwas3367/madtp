from digital_twin.twin_update import (
    DigitalTwinUpdater
)


class TwinDivergenceAnalyzer:
    """
    MADTP Twin-Reality Divergence Analyzer.

    This module compares:

        REAL OBSERVED WORKER
                  vs
        DIGITAL TWIN STATE

    The Digital Twin is generated by the actual
    Digital Twin synchronization layer.

    Main output:

        twin_divergence_index

    Higher divergence means that the current observed
    worker condition is becoming increasingly different
    from the state maintained by the Digital Twin.

    This module does NOT:
        - calculate final risk
        - perform future prediction
        - perform what-if simulation
        - train an AI model
    """

    def __init__(self, data, baseline):

        self.data = data.copy()

        self.baseline = baseline

        self.twin_updater = DigitalTwinUpdater(
            baseline
        )

        self.results = []


    # =====================================================
    # 1. VALIDATE INPUT
    # =====================================================

    def validate_data(self):

        required_columns = [

            "time",

            "heart_rate",

            "spo2",

            "body_temperature",

            "ambient_temperature",

            "humidity",

            "heat_load",

            "activity",

            "exposure_time",

            "physiological_state",

            "environmental_state",

            "activity_exposure_state",

            "temporal_deterioration",

            "unified_worker_state"
        ]

        missing_columns = [

            column

            for column in required_columns

            if column not in self.data.columns
        ]

        if missing_columns:

            raise ValueError(
                "Missing required columns: "
                +
                ", ".join(missing_columns)
            )


    # =====================================================
    # 2. CREATE OBSERVATION
    # =====================================================

    def create_observation(self, row):

        """
        Converts one dataframe row into the observation
        format expected by the Digital Twin updater.
        """

        observation = {

            "time":
                float(row["time"]),

            "heart_rate":
                float(row["heart_rate"]),

            "spo2":
                float(row["spo2"]),

            "body_temperature":
                float(row["body_temperature"]),

            "ambient_temperature":
                float(row["ambient_temperature"]),

            "humidity":
                float(row["humidity"]),

            "heat_load":
                float(row["heat_load"]),

            "activity":
                float(row["activity"]),

            "exposure_time":
                float(row["exposure_time"]),

            "physiological_state":
                float(row["physiological_state"]),

            "environmental_state":
                float(row["environmental_state"]),

            "activity_exposure_state":
                float(row[
                    "activity_exposure_state"
                ]),

            "temporal_deterioration":
                float(row[
                    "temporal_deterioration"
                ]),

            "unified_worker_state":
                float(row[
                    "unified_worker_state"
                ])
        }

        return observation


    # =====================================================
    # 3. NORMALIZE DIFFERENCE
    # =====================================================

    @staticmethod
    def normalized_difference(
        observed,
        twin,
        scale
    ):

        difference = abs(
            observed - twin
        )

        return float(
            np.clip(
                difference / scale,
                0,
                1
            )
        )


    # =====================================================
    # 4. CALCULATE PHYSIOLOGICAL DIVERGENCE
    # =====================================================

    def calculate_physiological_divergence(
        self,
        observation,
        twin_state
    ):

        physiological = (
            twin_state[
                "physiological"
            ]
        )


        hr_divergence = (
            self.normalized_difference(

                observation[
                    "heart_rate"
                ],

                physiological[
                    "heart_rate"
                ],

                30
            )
        )


        spo2_divergence = (
            self.normalized_difference(

                observation[
                    "spo2"
                ],

                physiological[
                    "spo2"
                ],

                4
            )
        )


        temperature_divergence = (
            self.normalized_difference(

                observation[
                    "body_temperature"
                ],

                physiological[
                    "body_temperature"
                ],

                1.0
            )
        )


        physiological_divergence = (

            0.40 * hr_divergence

            +

            0.20 * spo2_divergence

            +

            0.40 *
            temperature_divergence
        )


        return {

            "hr_divergence":
                hr_divergence,

            "spo2_divergence":
                spo2_divergence,

            "temperature_divergence":
                temperature_divergence,

            "physiological_divergence":
                float(
                    np.clip(
                        physiological_divergence,
                        0,
                        1
                    )
                )
        }


    # =====================================================
    # 5. CALCULATE ENVIRONMENTAL DIVERGENCE
    # =====================================================

    def calculate_environmental_divergence(
        self,
        observation,
        twin_state
    ):

        environment = (
            twin_state[
                "environmental"
            ]
        )


        temperature_divergence = (
            self.normalized_difference(

                observation[
                    "ambient_temperature"
                ],

                environment[
                    "ambient_temperature"
                ],

                10
            )
        )


        humidity_divergence = (
            self.normalized_difference(

                observation[
                    "humidity"
                ],

                environment[
                    "humidity"
                ],

                30
            )
        )


        heat_load_divergence = (
            self.normalized_difference(

                observation[
                    "heat_load"
                ],

                environment[
                    "heat_load"
                ],

                1
            )
        )


        environmental_divergence = (

            0.40 *
            temperature_divergence

            +

            0.30 *
            humidity_divergence

            +

            0.30 *
            heat_load_divergence
        )


        return {

            "environment_temperature_divergence":
                temperature_divergence,

            "humidity_divergence":
                humidity_divergence,

            "heat_load_divergence":
                heat_load_divergence,

            "environmental_divergence":
                float(
                    np.clip(
                        environmental_divergence,
                        0,
                        1
                    )
                )
        }


    # =====================================================
    # 6. CALCULATE ACTIVITY / EXPOSURE DIVERGENCE
    # =====================================================

    def calculate_activity_divergence(
        self,
        observation,
        twin_state
    ):

        activity_exposure = (
            twin_state[
                "activity_exposure"
            ]
        )


        activity_divergence = (
            self.normalized_difference(

                observation[
                    "activity"
                ],

                activity_exposure[
                    "activity_level"
                ],

                1
            )
        )


        return {

            "activity_divergence":
                activity_divergence
        }


    # =====================================================
    # 7. CALCULATE UNIFIED STATE DIVERGENCE
    # =====================================================

    def calculate_state_divergence(
        self,
        observation,
        twin_state
    ):

        twin_unified_state = (
            twin_state[
                "unified"
            ][
                "unified_worker_state"
            ]
        )


        state_difference = abs(

            observation[
                "unified_worker_state"
            ]

            -

            twin_unified_state
        )


        return float(
            np.clip(
                state_difference,
                0,
                1
            )
        )


    # =====================================================
    # 8. MAIN TWIN DIVERGENCE INDEX
    # =====================================================

    def calculate_divergence_index(
        self,
        physiological,
        environmental,
        activity,
        state
    ):

        """
        Multimodal Twin Divergence Index.

        The four components are combined to represent
        the overall difference between reality and
        the Digital Twin.
        """

        divergence = (

            0.35 *
            physiological[
                "physiological_divergence"
            ]

            +

            0.25 *
            environmental[
                "environmental_divergence"
            ]

            +

            0.15 *
            activity[
                "activity_divergence"
            ]

            +

            0.25 *
            state
        )


        return float(
            np.clip(
                divergence,
                0,
                1
            )
        )


    # =====================================================
    # 9. CLASSIFY DIVERGENCE
    # =====================================================

    @staticmethod
    def classify_divergence(value):

        if value < 0.10:

            return "ALIGNED"

        elif value < 0.25:

            return "LOW_DIVERGENCE"

        elif value < 0.45:

            return "MODERATE_DIVERGENCE"

        elif value < 0.70:

            return "HIGH_DIVERGENCE"

        else:

            return "SEVERE_DIVERGENCE"


    # =====================================================
    # 10. PROCESS COMPLETE DATASET
    # =====================================================

    def analyze(self):

        print("\n")
        print("=" * 60)
        print("      MADTP DIGITAL TWIN DIVERGENCE ENGINE")
        print("=" * 60)


        self.validate_data()

        print(
            "\n✓ Required observation features verified"
        )


        # -------------------------------------------------
        # Process every observation
        # -------------------------------------------------

        for _, row in self.data.iterrows():

            observation = (
                self.create_observation(row)
            )


            # ---------------------------------------------
            # Synchronize actual Digital Twin
            # ---------------------------------------------

            twin_state = (
                self.twin_updater.synchronize(
                    observation
                )
            )


            # ---------------------------------------------
            # Individual divergence components
            # ---------------------------------------------

            physiological = (
                self.calculate_physiological_divergence(

                    observation,

                    twin_state
                )
            )


            environmental = (
                self.calculate_environmental_divergence(

                    observation,

                    twin_state
                )
            )


            activity = (
                self.calculate_activity_divergence(

                    observation,

                    twin_state
                )
            )


            state_divergence = (
                self.calculate_state_divergence(

                    observation,

                    twin_state
                )
            )


            # ---------------------------------------------
            # Main divergence index
            # ---------------------------------------------

            divergence_index = (
                self.calculate_divergence_index(

                    physiological,

                    environmental,

                    activity,

                    state_divergence
                )
            )


            divergence_status = (
                self.classify_divergence(
                    divergence_index
                )
            )


            # ---------------------------------------------
            # Store result
            # ---------------------------------------------

            result = {

                "time":
                    observation["time"],

                "hr_divergence":
                    physiological[
                        "hr_divergence"
                    ],

                "spo2_divergence":
                    physiological[
                        "spo2_divergence"
                    ],

                "temperature_divergence":
                    physiological[
                        "temperature_divergence"
                    ],

                "physiological_divergence":
                    physiological[
                        "physiological_divergence"
                    ],

                "environmental_divergence":
                    environmental[
                        "environmental_divergence"
                    ],

                "activity_divergence":
                    activity[
                        "activity_divergence"
                    ],

                "state_divergence":
                    state_divergence,

                "twin_divergence_index":
                    divergence_index,

                "divergence_status":
                    divergence_status,

                # -----------------------------------------
                # Actual Twin state
                # -----------------------------------------

                "twin_heart_rate":
                    twin_state[
                        "physiological"
                    ][
                        "heart_rate"
                    ],

                "twin_spo2":
                    twin_state[
                        "physiological"
                    ][
                        "spo2"
                    ],

                "twin_body_temperature":
                    twin_state[
                        "physiological"
                    ][
                        "body_temperature"
                    ],

                "twin_ambient_temperature":
                    twin_state[
                        "environmental"
                    ][
                        "ambient_temperature"
                    ],

                "twin_humidity":
                    twin_state[
                        "environmental"
                    ][
                        "humidity"
                    ],

                "twin_heat_load":
                    twin_state[
                        "environmental"
                    ][
                        "heat_load"
                    ],

                "twin_unified_state":
                    twin_state[
                        "unified"
                    ][
                        "unified_worker_state"
                    ]
            }


            self.results.append(
                result
            )


        # -------------------------------------------------
        # Create dataframe
        # -------------------------------------------------

        divergence_data = pd.DataFrame(
            self.results
        )


        # -------------------------------------------------
        # Merge with original feature data
        # -------------------------------------------------

        original_data = (
            self.data.reset_index(
                drop=True
            )
        )


        divergence_data = pd.concat(

            [
                original_data,

                divergence_data.drop(
                    columns=["time"]
                )
            ],

            axis=1
        )


        # -------------------------------------------------
        # Clean numerical values
        # -------------------------------------------------

        divergence_data = (

            divergence_data

            .replace(
                [np.inf, -np.inf],
                np.nan
            )

            .ffill()

            .bfill()
        )


        self.results_dataframe = (
            divergence_data
        )


        print(
            "✓ Digital Twin synchronized "
            "for all observations"
        )

        print(
            "✓ Physiological divergence calculated"
        )

        print(
            "✓ Environmental divergence calculated"
        )

        print(
            "✓ Activity/exposure divergence calculated"
        )

        print(
            "✓ Unified-state divergence calculated"
        )

        print(
            "✓ Multimodal Twin Divergence Index generated"
        )

        print(
            "✓ Divergence status classified"
        )

        print(
            "\nTwin divergence analysis completed."
        )


        return divergence_data


