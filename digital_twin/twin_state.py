from dataclasses import dataclass, asdict


@dataclass
class PhysiologicalState:
    """
    Current physiological state of the worker
    maintained by the Digital Twin.
    """

    heart_rate: float = 0.0

    spo2: float = 0.0

    body_temperature: float = 0.0


@dataclass
class EnvironmentalState:
    """
    Current environmental state surrounding the worker.
    """

    ambient_temperature: float = 0.0

    humidity: float = 0.0

    heat_load: float = 0.0


@dataclass
class ActivityExposureState:
    """
    Represents the worker's activity and accumulated
    environmental exposure.
    """

    activity_level: float = 0.0

    exposure_time: float = 0.0

    cumulative_heat_exposure: float = 0.0


@dataclass
class TemporalState:
    """
    Stores short-term changes in the worker and
    environmental conditions.
    """

    heart_rate_change: float = 0.0

    body_temperature_change: float = 0.0

    spo2_change: float = 0.0

    environmental_change: float = 0.0

    state_change: float = 0.0


@dataclass
class UnifiedState:
    """
    Unified multimodal state generated by the
    feature-fusion stage.
    """

    physiological_state: float = 0.0

    environmental_state: float = 0.0

    activity_exposure_state: float = 0.0

    temporal_deterioration: float = 0.0

    unified_worker_state: float = 0.0


class DigitalTwinState:
    """
    Complete Digital Twin state.

    The Digital Twin contains four major state domains:

        1. Physiological
        2. Environmental
        3. Activity / Exposure
        4. Temporal

    It also stores the unified multimodal worker state.

    This class ONLY represents and stores the state.
    """

    def __init__(self):

        self.physiological = (
            PhysiologicalState()
        )

        self.environmental = (
            EnvironmentalState()
        )

        self.activity_exposure = (
            ActivityExposureState()
        )

        self.temporal = (
            TemporalState()
        )

        self.unified = (
            UnifiedState()
        )


    # =====================================================
    # UPDATE PHYSIOLOGICAL STATE
    # =====================================================

    def set_physiological_state(
        self,
        heart_rate,
        spo2,
        body_temperature
    ):

        self.physiological = (
            PhysiologicalState(

                heart_rate=float(
                    heart_rate
                ),

                spo2=float(
                    spo2
                ),

                body_temperature=float(
                    body_temperature
                )
            )
        )


    # =====================================================
    # UPDATE ENVIRONMENTAL STATE
    # =====================================================

    def set_environmental_state(
        self,
        ambient_temperature,
        humidity,
        heat_load
    ):

        self.environmental = (
            EnvironmentalState(

                ambient_temperature=float(
                    ambient_temperature
                ),

                humidity=float(
                    humidity
                ),

                heat_load=float(
                    heat_load
                )
            )
        )


    # =====================================================
    # UPDATE ACTIVITY / EXPOSURE
    # =====================================================

    def set_activity_exposure_state(
        self,
        activity_level,
        exposure_time,
        cumulative_heat_exposure
    ):

        self.activity_exposure = (
            ActivityExposureState(

                activity_level=float(
                    activity_level
                ),

                exposure_time=float(
                    exposure_time
                ),

                cumulative_heat_exposure=float(
                    cumulative_heat_exposure
                )
            )
        )


    # =====================================================
    # UPDATE TEMPORAL STATE
    # =====================================================

    def set_temporal_state(
        self,
        heart_rate_change,
        body_temperature_change,
        spo2_change,
        environmental_change,
        state_change
    ):

        self.temporal = (
            TemporalState(

                heart_rate_change=float(
                    heart_rate_change
                ),

                body_temperature_change=float(
                    body_temperature_change
                ),

                spo2_change=float(
                    spo2_change
                ),

                environmental_change=float(
                    environmental_change
                ),

                state_change=float(
                    state_change
                )
            )
        )


    # =====================================================
    # UPDATE UNIFIED STATE
    # =====================================================

    def set_unified_state(
        self,
        physiological_state,
        environmental_state,
        activity_exposure_state,
        temporal_deterioration,
        unified_worker_state
    ):

        self.unified = (
            UnifiedState(

                physiological_state=float(
                    physiological_state
                ),

                environmental_state=float(
                    environmental_state
                ),

                activity_exposure_state=float(
                    activity_exposure_state
                ),

                temporal_deterioration=float(
                    temporal_deterioration
                ),

                unified_worker_state=float(
                    unified_worker_state
                )
            )
        )


    # =====================================================
    # GET COMPLETE STATE
    # =====================================================

    def get_state(self):

        """
        Returns the complete Digital Twin state
        as a dictionary.

        This makes the state easy to pass to other
        modules such as worker_twin.py,
        twin_update.py and twin_divergence.py.
        """

        return {

            "physiological":
                asdict(
                    self.physiological
                ),

            "environmental":
                asdict(
                    self.environmental
                ),

            "activity_exposure":
                asdict(
                    self.activity_exposure
                ),

            "temporal":
                asdict(
                    self.temporal
                ),

            "unified":
                asdict(
                    self.unified
                )
        }


    # =====================================================
    # DISPLAY STATE
    # =====================================================

    def display(self):

        print("\n")
        print("=" * 60)
        print("             DIGITAL TWIN STATE")
        print("=" * 60)


        print("\nPHYSIOLOGICAL STATE")
        print("----------------------------------------")

        print(
            f"Heart Rate       : "
            f"{self.physiological.heart_rate:.2f} BPM"
        )

        print(
            f"SpO₂             : "
            f"{self.physiological.spo2:.2f} %"
        )

        print(
            f"Body Temperature : "
            f"{self.physiological.body_temperature:.3f} °C"
        )


        print("\nENVIRONMENTAL STATE")
        print("----------------------------------------")

        print(
            f"Ambient Temp     : "
            f"{self.environmental.ambient_temperature:.2f} °C"
        )

        print(
            f"Humidity         : "
            f"{self.environmental.humidity:.2f} %"
        )

        print(
            f"Heat Load        : "
            f"{self.environmental.heat_load:.3f}"
        )


        print("\nACTIVITY / EXPOSURE STATE")
        print("----------------------------------------")

        print(
            f"Activity Level   : "
            f"{self.activity_exposure.activity_level:.3f}"
        )

        print(
            f"Exposure Time    : "
            f"{self.activity_exposure.exposure_time:.1f} min"
        )

        print(
            f"Cumulative Heat  : "
            f"{self.activity_exposure.cumulative_heat_exposure:.3f}"
        )


        print("\nTEMPORAL STATE")
        print("----------------------------------------")

        print(
            f"HR Change        : "
            f"{self.temporal.heart_rate_change:.3f}"
        )

        print(
            f"Temp Change      : "
            f"{self.temporal.body_temperature_change:.4f}"
        )

        print(
            f"SpO₂ Change      : "
            f"{self.temporal.spo2_change:.3f}"
        )

        print(
            f"Environment Δ    : "
            f"{self.temporal.environmental_change:.3f}"
        )

        print(
            f"State Change     : "
            f"{self.temporal.state_change:.3f}"
        )


        print("\nUNIFIED WORKER STATE")
        print("----------------------------------------")

        print(
            f"Physiological    : "
            f"{self.unified.physiological_state:.3f}"
        )

        print(
            f"Environmental    : "
            f"{self.unified.environmental_state:.3f}"
        )

        print(
            f"Activity/Exposure: "
            f"{self.unified.activity_exposure_state:.3f}"
        )

        print(
            f"Temporal         : "
            f"{self.unified.temporal_deterioration:.3f}"
        )

        print(
            f"Unified State    : "
            f"{self.unified.unified_worker_state:.3f}"
        )

        print("----------------------------------------")


